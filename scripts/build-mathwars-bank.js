#!/usr/bin/env node
// Reproducible solo practice bank. Keep the original 102 hard questions and
// add 398 without changing the shared duel bank or its seeded scoring.
const { MATH_FIGHT_BANK } = require('../js/math-fight-bank');
const { warsIsEasyQuestion } = require('../js/mathwars');
const { makeRng } = require('../js/math-fight-rules');

const TARGETS = { '+': 223, '−': 222, '×': 42, ':': 13 };
const key = ([a, b, op]) => `${a}${op}${b}`;

function build() {
  const original = MATH_FIGHT_BANK.filter(([a, b, op, answer, tier]) =>
    tier <= 8 && !warsIsEasyQuestion({ a, b, op, answer }));
  if (original.length !== 102) throw new Error('Expected the original 102 hard questions');
  const out = original.map(entry => entry.slice());
  const seen = new Set(out.map(key));
  const random = makeRng(500398);
  for (const [op, target] of Object.entries(TARGETS)) {
    const candidates = [];
    for (let a = 1; a <= 99; a++) {
      for (let b = 1; b <= 99; b++) {
        const answer = op === '+' ? a + b : op === '−' ? a - b : op === '×' ? a * b : a / b;
        if (!Number.isInteger(answer) || answer < 10 || answer > 99) continue;
        if (warsIsEasyQuestion({ a, b, op, answer })) continue;
        const tier = Math.max(0, Math.ceil((Math.max(a, b, answer) - 19) / 10));
        const entry = [a, b, op, answer, tier];
        if (!seen.has(key(entry))) candidates.push(entry);
      }
    }
    for (let i = candidates.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [candidates[i], candidates[j]] = [candidates[j], candidates[i]];
    }
    const needed = target - out.filter(entry => entry[2] === op).length;
    if (needed < 0 || candidates.length < needed) throw new Error('Not enough questions for ' + op);
    for (const entry of candidates.slice(0, needed)) {
      seen.add(key(entry));
      out.push(entry);
    }
  }
  if (out.length !== 500 || seen.size !== 500) throw new Error('Expected 500 unique questions');
  return out;
}

function render(bank = build()) {
  return '// Generated by scripts/build-mathwars-bank.js. Solo practice only.\n' +
    '// 102 original hard questions + 398 new questions; all numbers <= 99.\n' +
    'var MATH_WARS_BANK = [\n' + bank.map(q => '  ' + JSON.stringify(q) + ',').join('\n') +
    '\n];\n\nif (typeof module !== \'undefined\' && module.exports) {\n' +
    '  module.exports = { MATH_WARS_BANK };\n}\n';
}

// Emit to stdout; the caller chooses where to save the generated artifact.
if (require.main === module) process.stdout.write(render());
module.exports = { build, render, TARGETS };
