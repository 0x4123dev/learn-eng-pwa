#!/usr/bin/env node
// build-tier-data.js — regenerate js/wordform-data.js and js/rewrite-data.js
// from data/wordform/ and data/rewrite/.
//
//   node scripts/build-tier-data.js              both
//   node scripts/build-tier-data.js wordform     one
//
//   data/<menu>/base.json          the original bank, all Không chuyên
//   data/<menu>/ch-add-NN.json     Chuyên items, 20 per file, one author each
//
// The two JS banks used to be written by hand. When their Chuyên tiers were
// authored by parallel agents they became build outputs: the base is frozen
// in base.json, every addition is a separate validated file with its own id
// range, and this emits the same header shape and exports the hand-written
// files had. A failing addition file fails the build; a duplicate id does too.
//
// Base items carry no `level` and are read as Không chuyên by the tabs
// (js/wordform.js, js/rewrite.js treat a missing level as 'kc'). Additions
// carry level "ch". The Chuyên items are in the same array as the rest — the
// tab decides at draw time, per child, whether they are in play.
'use strict';
const fs = require('fs');
const path = require('path');
const { validate } = require('./validate-tier.js');

const ROOT = path.join(__dirname, '..');
const BANKS = {
  wordform: {
    dir: 'data/wordform', out: 'js/wordform-data.js', name: 'WORDFORM_QUESTIONS',
    header: (n, ch) => `// wordform-data.js — Word-formation bank for the "Word form" tab.
// GENERATED by scripts/build-tier-data.js from data/wordform/ — do not edit
// by hand; edit base.json or a ch-add-NN.json file and rebuild.
//
// ${n - ch} Không chuyên questions (the original bank: 300 multiple-choice +
// 300 typed, generated and verified by multi-agent workflows) and ${ch}
// Chuyên questions (level "ch"), which a child meets only once an admin has
// switched Chuyên on for them — see js/wordform.js wordformBank().
// mcq: { id, [level], type:'mcq', cat, base, q, options[4], correct, answer, vi, explanation }
// text:{ id, [level], type:'text', cat, base, q, answer, accept[], vi, explanation }
`,
  },
  rewrite: {
    dir: 'data/rewrite', out: 'js/rewrite-data.js', name: 'REWRITE_QUESTIONS',
    header: (n, ch) => `// rewrite-data.js — Sentence-transformation bank for the "Rewrite" tab.
// GENERATED by scripts/build-tier-data.js from data/rewrite/ — do not edit
// by hand; edit base.json or a ch-add-NN.json file and rebuild.
//
// ${n - ch} Không chuyên questions across 25 structure types (the original
// bank, generated and verified by a 50-agent workflow) and ${ch} Chuyên
// key-word transformations (level "ch", cat "kwt": key, stem, tail), which a
// child meets only once an admin has switched Chuyên on for them.
// Schema: { id, [level], cat, catLabel, [key], orig, stem, [tail], answer, accept[], vi, explanation }.
// Graded case/punctuation/contraction-insensitively (see js/rewrite.js _rwNormalize).
`,
  },
};

const only = process.argv[2];
let failures = 0;
for (const kind of only ? [only] : Object.keys(BANKS)) {
  const b = BANKS[kind];
  if (!b) { console.error(`✗ unknown bank "${kind}"`); process.exit(2); }
  const dir = path.join(ROOT, b.dir);
  const base = JSON.parse(fs.readFileSync(path.join(dir, 'base.json'), 'utf8')).questions;
  const files = fs.readdirSync(dir).filter(f => /^ch-add-\d{2}\.json$/.test(f)).sort();
  let bad = 0;
  const added = [];
  for (const f of files) {
    const problems = validate(kind, path.join(dir, f));
    if (problems.length) { bad++; console.error(`✗ ${b.dir}/${f}: ${problems.length} problem(s)`); problems.slice(0, 12).forEach(m => console.error('   - ' + m)); continue; }
    added.push(...JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).questions);
  }
  const all = base.concat(added);
  const seen = new Set();
  for (const q of all) { if (seen.has(q.id)) { bad++; console.error(`✗ ${kind}: duplicate id ${q.id}`); } seen.add(q.id); }
  if (bad) { failures++; console.error(`✗ ${kind}: ${bad} failure(s); ${b.out} NOT written`); continue; }
  const ch = added.length;
  const body = `const ${b.name} = [\n` + all.map(q => '  ' + JSON.stringify(q)).join(',\n') + '\n];\n\n'
    + `if (typeof module !== 'undefined' && module.exports) { module.exports = { ${b.name} }; }\n`;
  fs.writeFileSync(path.join(ROOT, b.out), b.header(all.length, ch) + body);
  console.log(`✓ ${b.out}: ${all.length} questions (${all.length - ch} kc + ${ch} ch), ${files.length} addition file(s), ${(fs.statSync(path.join(ROOT, b.out)).size / 1024).toFixed(0)} kB`);
}
process.exit(failures ? 1 : 0);
