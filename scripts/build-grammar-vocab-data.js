#!/usr/bin/env node
// build-grammar-vocab-data.js — regenerate js/grammar-vocab-data.js from
// data/grammar-vocab/gv-NN.json.
//
//   node scripts/build-grammar-vocab-data.js
//
// Every file goes through scripts/validate-grammar-vocab.js first and one
// failing file fails the build; a duplicate id does too. Items keep file
// order, so the bank reads like its sources.
'use strict';
const fs = require('fs');
const path = require('path');
const { validate } = require('./validate-grammar-vocab.js');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'data', 'grammar-vocab');
const OUT = path.join(ROOT, 'js', 'grammar-vocab-data.js');

const files = fs.readdirSync(DIR).filter(f => /^gv-\d{2}\.json$/.test(f)).sort();
let failures = 0;
const all = [];
for (const f of files) {
  const problems = validate(path.join(DIR, f));
  if (problems.length) { failures++; console.error(`✗ ${f}: ${problems.length} problem(s)`); problems.slice(0, 12).forEach(m => console.error('   - ' + m)); continue; }
  all.push(...JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')).items);
}
const seen = new Set();
for (const q of all) { if (seen.has(q.id)) { failures++; console.error(`✗ duplicate id ${q.id}`); } seen.add(q.id); }
if (failures) { console.error(`\n${failures} failure(s); js/grammar-vocab-data.js NOT written`); process.exit(1); }

const kc = all.filter(q => q.level === 'kc').length, ch = all.length - kc;
const header = `// grammar-vocab-data.js — GENERATED by scripts/build-grammar-vocab-data.js. Do not edit.
// ${all.length} sentence-level multiple-choice items (${kc} Không chuyên, ${ch} Chuyên) in the
// format of the PTNK paper's "Language use" section — one blank, four options,
// mixed focuses (tense, modal, idiom, phrasal verb, collocation, …).
// Original material written for this app; see data/grammar-vocab/SCHEMA.md.
// Edit the JSON under data/grammar-vocab/ and rebuild.
`;
fs.writeFileSync(OUT, header + 'const GRAMMAR_VOCAB_ITEMS = ' + JSON.stringify(all, null, 1) + ';\n\n'
  + "if (typeof module !== 'undefined' && module.exports) { module.exports = { GRAMMAR_VOCAB_ITEMS }; }\n");
console.log(`✓ js/grammar-vocab-data.js: ${all.length} items (${kc} kc + ${ch} ch), ${files.length} file(s), ${(fs.statSync(OUT).size / 1024).toFixed(0)} kB`);
