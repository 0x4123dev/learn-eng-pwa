#!/usr/bin/env node
// build-practice-data.js — assemble the three PTNK-format practice banks.
//
//   node scripts/build-practice-data.js            builds all three
//   node scripts/build-practice-data.js reading    just one
//
//   data/reading/reading-NN.json  →  js/reading-data.js  (READING_PASSAGES)
//   data/cloze/cloze-NN.json      →  js/cloze-data.js    (CLOZE_PASSAGES)
//   data/errors/errors-NN.json    →  js/errors-data.js   (ERROR_ITEMS)
//
// Every source file goes through scripts/validate-practice.js first, and one
// failing file fails the build — a bank with a hole in it would list fewer
// passages than a child was promised and nobody would know which.
// Duplicate ids across files fail too: the id is the paper id the history and
// the daily-task matcher key on. The outputs are GENERATED; edit the JSON.
'use strict';
const fs = require('fs');
const path = require('path');
const { validate } = require('./validate-practice.js');

const ROOT = path.join(__dirname, '..');
const BANKS = {
  reading: { dir: 'data/reading', re: /^reading-\d{2}\.json$/, list: 'passages', out: 'js/reading-data.js', name: 'READING_PASSAGES', label: 'reading passages' },
  cloze: { dir: 'data/cloze', re: /^cloze-\d{2}\.json$/, list: 'passages', out: 'js/cloze-data.js', name: 'CLOZE_PASSAGES', label: 'cloze texts' },
  errors: { dir: 'data/errors', re: /^errors-\d{2}\.json$/, list: 'items', out: 'js/errors-data.js', name: 'ERROR_ITEMS', label: 'error-identification items' },
};

const only = process.argv[2];
const kinds = only ? [only] : Object.keys(BANKS);
let failures = 0;

for (const kind of kinds) {
  const b = BANKS[kind];
  if (!b) { console.error(`✗ unknown bank "${kind}"`); process.exit(2); }
  const dir = path.join(ROOT, b.dir);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => b.re.test(f)).sort() : [];
  if (!files.length) { console.error(`✗ ${kind}: no ${b.dir}/*.json files`); failures++; continue; }
  const items = [];
  const seen = new Set();
  let bad = 0;
  for (const f of files) {
    const file = path.join(dir, f);
    const problems = validate(kind, file);
    if (problems.length) {
      bad++;
      console.error(`✗ ${b.dir}/${f}: ${problems.length} problem(s)`);
      problems.slice(0, 12).forEach(m => console.error('   - ' + m));
      continue;
    }
    for (const it of JSON.parse(fs.readFileSync(file, 'utf8'))[b.list]) {
      if (seen.has(it.id)) { bad++; console.error(`✗ ${b.dir}/${f}: duplicate id ${it.id}`); continue; }
      seen.add(it.id);
      items.push(it);
    }
  }
  if (bad) { failures++; console.error(`✗ ${kind}: ${bad} failure(s); ${b.out} NOT written`); continue; }
  // Không chuyên first, then Chuyên; stable within a level by id.
  items.sort((x, y) => (x.level === y.level ? (x.id < y.id ? -1 : 1) : (x.level === 'kc' ? -1 : 1)));
  const kc = items.filter(i => i.level === 'kc').length;
  const questions = items.reduce((s, i) => s + (i.questions ? i.questions.length : 1), 0);
  const header = `// ${path.basename(b.out)} — GENERATED by scripts/build-practice-data.js. Do not edit.
// ${items.length} ${b.label} (${kc} Không chuyên, ${items.length - kc} Chuyên), ${questions} questions.
// Original material written for this app in the PTNK paper's formats; see
// data/reading/SCHEMA.md. Edit the JSON under ${b.dir}/ and rebuild.
// Written compact (no indentation): the file is read by machines only, and
// the pretty-printed layout cost ~10% of the raw download for nothing.
`;
  const body = `const ${b.name} = ` + JSON.stringify(items) + ';\n'
    + `if (typeof module !== 'undefined' && module.exports) module.exports = { ${b.name} };\n`;
  fs.writeFileSync(path.join(ROOT, b.out), header + body);
  console.log(`✓ ${b.out}: ${items.length} ${b.label} (${kc} kc / ${items.length - kc} ch), ${questions} questions, ${(fs.statSync(path.join(ROOT, b.out)).size / 1024).toFixed(0)} kB`);
}
process.exit(failures ? 1 : 0);
