#!/usr/bin/env node
// scripts/build-ptnk-data.js — assemble js/ptnk-data.js from the per-paper
// files under data/ptnk/.
//
//   node scripts/build-ptnk-data.js            (reads data/ptnk/ptnk-*.json)
//
// Every paper is put through scripts/validate-ptnk.js first — the same checks
// a transcriber ran on its own output — and one failing paper fails the build
// rather than shipping a bank with a hole in it. The PTNK tab would not crash
// on a missing paper; it would quietly list ten where there should be eleven,
// and nobody would know which one a child could no longer open.
//
// Papers are emitted newest first, Không chuyên before Chuyên within a year,
// which is the order the home screen shows them. js/ptnk-data.js is GENERATED
// — edit the JSON under data/ptnk/ and rerun this.
'use strict';

const fs = require('fs');
const path = require('path');
const { validate, PAPERS } = require('./validate-ptnk.js');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'data', 'ptnk');
const OUT = path.join(ROOT, 'js', 'ptnk-data.js');

const files = fs.readdirSync(SRC).filter(f => /^ptnk-\d{4}-(kc|chuyen)\.json$/.test(f)).sort();
if (!files.length) { console.error('✗ no data/ptnk/ptnk-*.json files'); process.exit(1); }

let failures = 0;
const papers = [];
for (const f of files) {
  const file = path.join(SRC, f);
  const problems = validate(file);
  if (problems.length) {
    failures++;
    console.error(`✗ ${f}: ${problems.length} problem(s)`);
    problems.slice(0, 20).forEach(m => console.error('   - ' + m));
    continue;
  }
  papers.push(JSON.parse(fs.readFileSync(file, 'utf8')));
}
// A paper on the fixed list with no file is a build error too: the catalog
// (js/daily-task-catalog.js) offers every id on that list as a daily task, and
// a task for a paper that is not in the bank deep-links to nothing.
const missing = Object.keys(PAPERS).filter(id => !papers.some(p => p.id === id));
if (missing.length) {
  failures++;
  console.error('✗ papers on the fixed list with no file: ' + missing.join(', '));
}
if (failures) { console.error(`\n${failures} failure(s); js/ptnk-data.js NOT written`); process.exit(1); }

papers.sort((a, b) => (b.year - a.year) || ((a.track === 'kc' ? 0 : 1) - (b.track === 'kc' ? 0 : 1)));
const total = papers.reduce((s, p) => s + p.questions.length, 0);

// SCHEMA.md has every question of a passage carry the passage in full (the
// engine draws one question at a time), so a source paper is mostly the same
// text ten times over: 1.2 MB of repeats against 144 kB of unique passage in
// the eleven papers. The source files stay that way — the transcribers, the
// assembler and the validator all work per question — but the shipped bank
// holds each passage once, in `passages`, and each question points at it by
// `passageId`. js/ptnk.js (ptnkHydrate) puts `passage` back on every question
// before a paper reaches js/exam.js, in the same key position, so the engine
// and the checkpoint see exactly the source shape.
function hoistPassages(paper) {
  const passages = [];
  const index = new Map();
  const questions = paper.questions.map(q => {
    if (typeof q.passage !== 'string') return q;
    let id = index.get(q.passage);
    if (id === undefined) { id = passages.length; passages.push(q.passage); index.set(q.passage, id); }
    const out = {};
    for (const k of Object.keys(q)) {
      if (k === 'passage') out.passageId = id; else out[k] = q[k];
    }
    return out;
  });
  if (!passages.length) return paper;
  const out = {};
  for (const k of Object.keys(paper)) {
    if (k === 'questions') { out.passages = passages; out.questions = questions; } else out[k] = paper[k];
  }
  return out;
}
const built = papers.map(hoistPassages);

const header = `// ptnk-data.js — GENERATED by scripts/build-ptnk-data.js. Do not edit.
// The real Phổ thông Năng khiếu grade-10 entrance English papers, transcribed
// from the scanned originals under data/ptnk/. ${papers.length} papers, ${total} questions.
// keySource "official" = answers from the published key; "solved" = worked
// out and cross-checked by two independent readers (2024–2026, no key exists).
// Each paper's passages are stored once in \`passages\`; a question points at
// its passage by \`passageId\`. js/ptnk.js ptnkHydrate() restores \`passage\`.
`;
// Compact JSON: this file is generated, read by machines, and every byte is
// downloaded by a child on a phone before the PTNK tab can open.
const body = 'const PTNK_EXAMS = ' + JSON.stringify(built) + ';\n'
  + "if (typeof module !== 'undefined' && module.exports) module.exports = { PTNK_EXAMS };\n";
fs.writeFileSync(OUT, header + body);
console.log(`✓ js/ptnk-data.js: ${papers.length} papers, ${total} questions, ${(fs.statSync(OUT).size / 1024).toFixed(0)} kB`);
papers.forEach(p => console.log(`   ${p.id.padEnd(18)} ${String(p.questions.length).padStart(3)} q  ${p.keySource}`));
