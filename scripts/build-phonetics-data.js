#!/usr/bin/env node
// build-phonetics-data.js — regenerate js/phonetics-data.js and
// js/phonetics-lessons.js from data/phonetics/.
//
//   node scripts/build-phonetics-data.js
//
// Every file goes through scripts/validate-phonetics.js first; one failing
// file fails the build, a duplicate id does too. Lessons keep file order.
'use strict';
const fs = require('fs');
const path = require('path');
const { validateBank, validateLesson } = require('./validate-phonetics.js');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'data', 'phonetics');
let failures = 0;

const files = fs.readdirSync(DIR).filter(f => /^ph-\d{2}\.json$/.test(f)).sort();
const all = [];
for (const f of files) {
  const problems = validateBank(path.join(DIR, f));
  if (problems.length) { failures++; console.error(`✗ ${f}: ${problems.length} problem(s)`); problems.slice(0, 12).forEach(m => console.error('   - ' + m)); continue; }
  all.push(...JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')).items);
}
const seen = new Set();
for (const q of all) { if (seen.has(q.id)) { failures++; console.error(`✗ duplicate id ${q.id}`); } seen.add(q.id); }

const lfiles = fs.readdirSync(path.join(DIR, 'lessons')).filter(f => /^lesson-\d{2}\.json$/.test(f)).sort();
const lessons = [];
for (const f of lfiles) {
  const problems = validateLesson(path.join(DIR, 'lessons', f));
  if (problems.length) { failures++; console.error(`✗ lessons/${f}: ${problems.length} problem(s)`); problems.slice(0, 12).forEach(m => console.error('   - ' + m)); continue; }
  lessons.push(JSON.parse(fs.readFileSync(path.join(DIR, 'lessons', f), 'utf8')));
}
const lkeys = new Set();
for (const l of lessons) { if (lkeys.has(l.key)) { failures++; console.error(`✗ duplicate lesson key ${l.key}`); } lkeys.add(l.key); }
if (failures) { console.error(`\n${failures} failure(s); nothing written`); process.exit(1); }

const kc = all.filter(q => q.level === 'kc').length, sound = all.filter(q => q.kind === 'sound').length;
fs.writeFileSync(path.join(ROOT, 'js', 'phonetics-data.js'), `// phonetics-data.js — GENERATED by scripts/build-phonetics-data.js. Do not edit.
// ${all.length} odd-one-out items (${sound} pronunciation, ${all.length - sound} word stress; ${kc} Không chuyên,
// ${all.length - kc} Chuyên) in the format of the PTNK paper's opening section. Original
// material written for this app; see data/phonetics/SCHEMA.md. Edit the JSON
// under data/phonetics/ and rebuild.
const PHONETICS_ITEMS = ${JSON.stringify(all, null, 1)};

if (typeof module !== 'undefined' && module.exports) { module.exports = { PHONETICS_ITEMS }; }
`);
fs.writeFileSync(path.join(ROOT, 'js', 'phonetics-lessons.js'), `// phonetics-lessons.js — GENERATED by scripts/build-phonetics-data.js. Do not edit.
// ${lessons.length} lessons for the Phonetics & Stress tab: the pronunciation and word-stress
// rules a grade-9 child needs for the PTNK paper's opening section, in Vietnamese
// with IPA. Edit data/phonetics/lessons/ and rebuild.
const PHONETICS_LESSONS = ${JSON.stringify(lessons, null, 1)};

if (typeof module !== 'undefined' && module.exports) { module.exports = { PHONETICS_LESSONS }; }
`);
console.log(`✓ js/phonetics-data.js: ${all.length} items (${kc} kc + ${all.length - kc} ch; ${sound} sound + ${all.length - sound} stress), ${files.length} file(s)`);
console.log(`✓ js/phonetics-lessons.js: ${lessons.length} lessons`);
