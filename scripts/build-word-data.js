#!/usr/bin/env node
// build-word-data.js — regenerate js/word-data.js from data/career-paths/.
//
//   node scripts/build-word-data.js
//   node scripts/build-word-data.js --out /tmp/word-data.js   (write elsewhere: the test's stale check)
//
//   data/career-paths/pr<book>-u<NN>.json   one file per BOOK unit (8 + 15 + 15)
//
// Book 1 is EIGHT practice units, one per book unit, about thirty words each
// (the printed Vocabulary list plus the rest of the new words on that unit's
// two pages — re-cut 2026-09-23). Books 2 and 3 are SEVEN: their fifteen are
// merged two-by-two (1-2, 3-4, … 11-12) and the last three together
// (13-15), the way the Grade 4 sets once merged their textbook units. Each
// word keeps its book unit (`bookUnit`) so the card can say which pages it
// covers ("Bài 3-4"); `unit` is the practice unit the app keys everything
// on (history, mastery, owed words, daily tasks: 'pr2-4').
//
// The Word tab's bank. Each unit file is validated (scripts/validate-word-data.js)
// before anything is written; a failing file fails the build, and so does a
// missing unit — each book's units are fixed (SHAPE) and the cards say so.
// Emits the same shape the hand-written Grade 4 banks have (js/units-hk2-data.js):
// { unit, book, en, vi, emoji, ex, exVi } per word, one array per set, plus
// the unit titles the cards print.
'use strict';
const fs = require('fs');
const path = require('path');
const { validateFile } = require('./validate-word-data.js');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'data', 'career-paths');
const DEFAULT_OUT = path.join(ROOT, 'js', 'word-data.js');
const BOOKS = [1, 2, 3];
// Each book says how many of its own units it carries and how they land on
// the practice units the app keys everything on.
//   Book 1 (re-cut 2026-09-23): the first EIGHT units of the book, one
//     practice unit each, about thirty words per unit — the printed
//     Vocabulary list plus the rest of the new words on that unit's pages.
//   Books 2 and 3: fifteen units merged two-by-two (1-2, 3-4, … 11-12) with
//     the last three together (13-15), carrying the printed list alone.
const SHAPE = {
  1: { units: 8, practice: 8, of: u => u },
  2: { units: 15, practice: 7, of: u => Math.min(7, Math.ceil(u / 2)) },
  3: { units: 15, practice: 7, of: u => Math.min(7, Math.ceil(u / 2)) },
};
const UNITS_PER_BOOK = { 1: SHAPE[1].units, 2: SHAPE[2].units, 3: SHAPE[3].units };
const PRACTICE_UNITS = { 1: SHAPE[1].practice, 2: SHAPE[2].practice, 3: SHAPE[3].practice };
function practiceUnitOf(bookUnit, book) { return SHAPE[book || 2].of(bookUnit); }

function build(outFile) {
  const OUT = outFile || DEFAULT_OUT;
  const problems = [];
  const sets = {};
  const titles = {};   // practice unit → 'Title A · Title B'
  const books = {};    // practice unit → [book units]
  for (const book of BOOKS) {
    const set = 'pr' + book;
    sets[set] = [];
    titles[set] = {};
    books[set] = {};
    for (let bookUnit = 1; bookUnit <= SHAPE[book].units; bookUnit++) {
      const file = path.join(DIR, `pr${book}-u${String(bookUnit).padStart(2, '0')}.json`);
      if (!fs.existsSync(file)) { problems.push(`${path.relative(ROOT, file)}: missing`); continue; }
      const bad = validateFile(file);
      if (bad.length) { problems.push(...bad.map(m => `${path.relative(ROOT, file)}: ${m}`)); continue; }
      const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
      const unit = practiceUnitOf(bookUnit, book);
      titles[set][unit] = titles[set][unit] ? titles[set][unit] + ' · ' + doc.title : doc.title;
      (books[set][unit] = books[set][unit] || []).push(bookUnit);
      for (const w of doc.words) sets[set].push({ unit, book, bookUnit, en: w.en, vi: w.vi, emoji: w.emoji, ex: w.ex, exVi: w.exVi });
    }
  }
  if (problems.length) {
    console.error('build-word-data: refusing to write js/word-data.js');
    for (const m of problems) console.error('  - ' + m);
    return 1;
  }

  const lit = v => JSON.stringify(v);
  const total = BOOKS.reduce((n, b) => n + sets['pr' + b].length, 0);
  let out = `// word-data.js — the Word tab's bank: Career Paths: Public Relations
// (Express Publishing, Virginia Evans / Jenny Dooley / Max Bloom), Books 1-3.
// GENERATED by scripts/build-word-data.js from data/career-paths/ — do not
// edit by hand; edit a pr<book>-u<NN>.json file and rebuild.
//
// Book 1: its first EIGHT units, one practice unit each, about thirty words
// per unit. Books 2 and 3: fifteen units carrying EXACTLY the Vocabulary
// column of the book's Scope and Sequence page, merged into SEVEN practice
// units (1-2, 3-4, …, 13-15). ${total} words in all. Shape: { unit, book,
// bookUnit, en, vi, emoji,
// ex, exVi } — emoji is the "picture", vi the Vietnamese meaning in the PR
// sense the book's Glossary gives, ex a sentence that uses the word (shown
// with the word blanked while answering) and exVi its translation (shown
// after). Loaded lazily with the Word tab (js/lazy-data.js
// SCREEN_FILES.wordScreen); js/units.js reads it through unitsBank('pr1'..).

`;
  out += `const UNIT_PR_TITLES = {\n`;
  for (const book of BOOKS) {
    const set = 'pr' + book;
    out += `  ${set}: {\n`;
    for (let unit = 1; unit <= SHAPE[book].practice; unit++) out += `    ${unit}: ${lit(titles[set][unit])},\n`;
    out += `  },\n`;
  }
  out += `};\n\n`;
  out += `// Which of the book's own units each practice unit covers.\nconst UNIT_PR_BOOKS = {\n`;
  for (const book of BOOKS) {
    const set = 'pr' + book;
    out += `  ${set}: {\n`;
    for (let unit = 1; unit <= SHAPE[book].practice; unit++) out += `    ${unit}: ${lit(books[set][unit])},\n`;
    out += `  },\n`;
  }
  out += `};\n\n`;
  for (const book of BOOKS) {
    const set = 'pr' + book;
    out += `// ══ Book ${book} — ${sets[set].length} words ══\nconst UNIT_WORDS_PR${book} = [\n`;
    let last = 0;
    for (const w of sets[set]) {
      if (w.bookUnit !== last) { out += `  // Book unit ${w.bookUnit} → practice unit ${w.unit}\n`; last = w.bookUnit; }
      out += `  { unit: ${w.unit}, book: ${book}, bookUnit: ${w.bookUnit}, en: ${lit(w.en)}, vi: ${lit(w.vi)}, emoji: ${lit(w.emoji)},\n    ex: ${lit(w.ex)}, exVi: ${lit(w.exVi)} },\n`;
    }
    out += `];\n\n`;
  }
  out += `if (typeof module !== 'undefined' && module.exports) {
  module.exports = { UNIT_PR_TITLES, UNIT_PR_BOOKS, UNIT_WORDS_PR1, UNIT_WORDS_PR2, UNIT_WORDS_PR3 };
}
`;
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${BOOKS.map(b => `Book ${b} = ${sets['pr' + b].length}`).join(', ')} (${total} words)`);
  return 0;
}

if (require.main === module) {
  const i = process.argv.indexOf('--out');
  process.exit(build(i > 0 ? path.resolve(process.argv[i + 1]) : undefined));
}
module.exports = { build, practiceUnitOf, PRACTICE_UNITS, UNITS_PER_BOOK };
