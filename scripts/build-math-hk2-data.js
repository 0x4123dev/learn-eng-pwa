#!/usr/bin/env node
// build-math-hk2-data.js — regenerate js/math-data-hk2.js from data/math-hk2/.
//
//   node scripts/build-math-hk2-data.js
//
//   data/math-hk2/base.json           the 500 original questions (m6-1…m10-100)
//   data/math-hk2/ch<N>-add-<NN>.json additions, 20 per file, one author each
//
// js/math-data-hk2.js used to be written by hand. When chapters 6 and 7 were
// tripled by parallel authors it became a build output: the base is frozen in
// base.json, every addition is a separate validated file, and this script
// emits the same header, chapter list, typed-number conversion and exports
// the hand-written file had — so nothing that reads it can tell.
//
// Every addition file goes through scripts/validate-math-hk2.js first and one
// failing file fails the build. Ids must be unique across base and additions,
// and every addition's id must sit in its file's own range, so two authors
// can never write over each other.
'use strict';
const fs = require('fs');
const path = require('path');
const { validate } = require('./validate-math-hk2.js');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'data', 'math-hk2');
const OUT = path.join(ROOT, 'js', 'math-data-hk2.js');

const base = JSON.parse(fs.readFileSync(path.join(DIR, 'base.json'), 'utf8'));
const files = fs.readdirSync(DIR).filter(f => /^ch\d-add-\d{2}\.json$/.test(f)).sort();

let failures = 0;
const additions = [];
for (const f of files) {
  const problems = validate(path.join(DIR, f));
  if (problems.length) {
    failures++;
    console.error(`✗ ${f}: ${problems.length} problem(s)`);
    problems.slice(0, 12).forEach(m => console.error('   - ' + m));
    continue;
  }
  additions.push(...JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')).questions);
}
const all = base.questions.concat(additions);
const seen = new Set();
for (const q of all) {
  if (seen.has(q.id)) { failures++; console.error(`✗ duplicate id ${q.id}`); }
  seen.add(q.id);
}
if (failures) { console.error(`\n${failures} failure(s); js/math-data-hk2.js NOT written`); process.exit(1); }

// Chapter order, then id number, so the file reads like the bank it is.
all.sort((a, b) => (a.ch - b.ch) || (Number(a.id.split('-')[1]) - Number(b.id.split('-')[1])));
const perCh = {};
all.forEach(q => { perCh[q.ch] = (perCh[q.ch] || 0) + 1; });

const header = `// math-data-hk2.js — Toán 7 Học kì 2, ngân hàng luyện tập 5 chương (VI…X).
// GENERATED by scripts/build-math-hk2-data.js from data/math-hk2/ — do not
// edit by hand; edit base.json or an addition file and rebuild.
//
// Cùng hình dạng với js/math-data.js (học kì 1) để mọi thứ dùng chung được:
// quiz, lịch sử, gợi ý, drill câu sai, thống kê năng lực. Khác duy nhất là
// số chương — HK1 dùng 1..5, HK2 dùng 6..10 — nên một câu hỏi tự nói nó
// thuộc học kì nào và không cần cờ riêng.
//
// Câu hỏi:
//   trắc nghiệm: { id, ch, topic, q, options[4], correct, answer, explanation, fig? }
//   tự nhập số: { id, ch, topic, q, type:'calc', keys:[], answer, explanation, fig? }
//   explanation: '🔑 quy tắc + kết quả<br>✗ vì sao A sai<br>✗ B<br>✗ C'
//   fig: đặc tả hình SVG do js/math-figures.js vẽ — KHÔNG dùng ảnh chụp.
//
// Nội dung các dạng bài bám theo 32 đề thi HK2 thật (2025-2026) của 14
// trường, đã được phân loại theo chương SGK Kết nối tri thức Tập hai.
// Chương 6 và 7 được nhân ba ngày 2026-09-11 bởi các tác giả song song, mỗi
// tệp bổ sung được một người giải mù kiểm lại từng đáp án.
// ${Object.keys(perCh).map(ch => `Chương ${ch}: ${perCh[ch]} câu`).join(' · ')} — tổng ${all.length}.

`;
const chapters = 'const MATH_CHAPTERS_HK2 = ' + JSON.stringify(base.chapters, null, 2) + ';\n\n';
const questions = 'const MATH_QUESTIONS_HK2 = ' + JSON.stringify(all, null, 1) + ';\n\n';
const tail = `// Câu chỉ có một đáp án số thì để bé TỰ TÍNH rồi nhập, không chọn trong bốn
// phương án: một câu tính toán mà đáp án nằm sẵn trước mắt thì không còn đo
// được bé có tính được hay không. Ở đây bất kỳ câu nào có đáp án là đúng một
// số (nguyên có dấu, hoặc phân số tối giản) đều được đổi thành tự nhập.
//
// Khuôn này cố ý chấp nhận số nguyên có dấu và phân số tối giản. Nếu sau này
// thêm số thập phân, tác giả phải duyệt và mở khuôn có chủ ý thay vì vô tình
// biến một câu mới thành tự nhập.
const MATH_HK2_TYPED_NUMBER_RE = /^[−-]?\\d+(?:\\/\\d+)?$/;
MATH_QUESTIONS_HK2.forEach(q => {
  if (!MATH_HK2_TYPED_NUMBER_RE.test(String(q.answer || '').trim())) return;
  q.type = 'calc';
  q.keys = [];
  delete q.options;
  delete q.correct;
});

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { MATH_CHAPTERS_HK2, MATH_QUESTIONS_HK2, MATH_HK2_TYPED_NUMBER_RE };
}
`;
fs.writeFileSync(OUT, header + chapters + questions + tail);
console.log(`✓ js/math-data-hk2.js: ${all.length} questions (${Object.keys(perCh).map(ch => 'ch' + ch + '=' + perCh[ch]).join(', ')}), ${(fs.statSync(OUT).size / 1024).toFixed(0)} kB, ${files.length} addition file(s)`);
